CREATE TABLE IF NOT EXISTS `junior_high_school` (
  `id` int NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `name` varchar(100) NOT NULL COMMENT '学校全名',
  `short_name` varchar(100) DEFAULT NULL COMMENT '学校简称',
  `background_image_url` varchar(500) DEFAULT NULL COMMENT '校园风光背景图（禁止校徽）',
  `district` varchar(50) NOT NULL COMMENT '所属区',
  `tuition_min` decimal(10,2) DEFAULT NULL COMMENT '最低学费',
  `tuition_max` decimal(10,2) DEFAULT NULL COMMENT '最高学费',
  `boarding_info` varchar(100) DEFAULT NULL COMMENT '住宿信息',
  `school_type` varchar(20) NOT NULL COMMENT '公办初中/民办初中',
  `address` varchar(255) DEFAULT NULL COMMENT '学校地址',
  `description` text COMMENT '学校简介',
  `official_website` varchar(500) DEFAULT NULL COMMENT '学校官网',
  `schedule` text COMMENT '作息时间',
  `teaching_features` text COMMENT '教学特色',
  `campus_area` decimal(12,2) DEFAULT NULL COMMENT '占地面积（平方米）',
  `created_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_junior_school_name_district` (`name`,`district`),
  KEY `idx_junior_school_district` (`district`),
  KEY `idx_junior_school_type` (`school_type`),
  CONSTRAINT `chk_junior_school_type` CHECK (`school_type` IN ('公办初中','民办初中')),
  CONSTRAINT `chk_junior_school_tuition` CHECK (`tuition_min` IS NULL OR `tuition_max` IS NULL OR `tuition_min` <= `tuition_max`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='普通初中学校信息';
