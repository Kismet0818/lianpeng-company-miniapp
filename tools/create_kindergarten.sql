CREATE TABLE IF NOT EXISTS `kindergarten` (
  `id` int NOT NULL AUTO_INCREMENT COMMENT '数据库主键ID，从10000001开始；跨表使用时必须同时携带schoolSource=kindergarten',
  `school_code` varchar(16) NOT NULL COMMENT '幼儿园唯一业务编号，例如k001、k002',
  `source_school_id` bigint NOT NULL COMMENT '来源平台幼儿园ID，用于幂等更新和去重',
  `name` varchar(100) NOT NULL COMMENT '幼儿园全名',
  `short_name` varchar(100) DEFAULT NULL COMMENT '幼儿园简称',
  `background_image_url` varchar(500) DEFAULT NULL COMMENT '背景图或封面图URL',
  `district` varchar(50) NOT NULL COMMENT '所属区',
  `tuition_min` decimal(10,2) DEFAULT NULL COMMENT '最低学费（万元/年）',
  `tuition_max` decimal(10,2) DEFAULT NULL COMMENT '最高学费（万元/年）',
  `school_type` varchar(20) NOT NULL COMMENT '办园性质：公办/民办',
  `kindergarten_level` varchar(30) DEFAULT NULL COMMENT '园所等级：示范园/一级园/二级园等',
  `care_type` varchar(30) DEFAULT NULL COMMENT '办园形式：全日制/半日制/寄宿制等',
  `age_range` varchar(50) DEFAULT NULL COMMENT '招生年龄范围',
  `address` varchar(255) DEFAULT NULL COMMENT '园所地址',
  `phone` varchar(100) DEFAULT NULL COMMENT '联系电话',
  `description` text COMMENT '园所简介',
  `official_website` varchar(500) DEFAULT NULL COMMENT '官方网站',
  `schedule` text COMMENT '作息时间',
  `teaching_features` text COMMENT '课程或教学特色',
  `campus_area` decimal(12,2) DEFAULT NULL COMMENT '占地面积（平方米）',
  `is_active` tinyint(1) NOT NULL DEFAULT 1 COMMENT '是否启用：1启用，0停用',
  `created_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_kindergarten_code` (`school_code`),
  UNIQUE KEY `uk_kindergarten_source_id` (`source_school_id`),
  UNIQUE KEY `uk_kindergarten_name_district` (`name`,`district`),
  KEY `idx_kindergarten_district` (`district`),
  KEY `idx_kindergarten_type` (`school_type`),
  KEY `idx_kindergarten_level` (`kindergarten_level`),
  CONSTRAINT `chk_kindergarten_code` CHECK (regexp_like(`school_code`, _utf8mb4'^k[0-9]{3,}$')),
  CONSTRAINT `chk_kindergarten_tuition` CHECK (`tuition_min` IS NULL OR `tuition_max` IS NULL OR `tuition_min` <= `tuition_max`),
  CONSTRAINT `chk_kindergarten_type` CHECK (`school_type` IN (_utf8mb4'公办', _utf8mb4'民办'))
) ENGINE=InnoDB AUTO_INCREMENT=10000001 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='幼儿园信息表（独立ID号段）';
