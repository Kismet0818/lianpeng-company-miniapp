CREATE TABLE IF NOT EXISTS zhongkao_resource_file (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '资源ID',
    resource_code VARCHAR(64) NOT NULL COMMENT '稳定业务编号',
    title VARCHAR(255) NOT NULL COMMENT '资料标题',
    resource_category VARCHAR(50) NOT NULL COMMENT '中考真题卷/自招配套资料',
    subject_category VARCHAR(50) NOT NULL COMMENT '学科或用途分类',
    resource_type VARCHAR(50) NOT NULL COMMENT '真题/答案/范文/模板/信息汇总/其他',
    target_year VARCHAR(10) NOT NULL DEFAULT '2026' COMMENT '适用届别',
    source_year VARCHAR(10) DEFAULT NULL COMMENT '资料原始年份',
    original_file_name VARCHAR(255) NOT NULL COMMENT '原文件名',
    relative_path VARCHAR(1000) NOT NULL COMMENT '来源包内相对路径',
    file_extension VARCHAR(20) NOT NULL COMMENT '文件扩展名',
    mime_type VARCHAR(150) NOT NULL COMMENT 'MIME类型',
    file_size BIGINT NOT NULL COMMENT '文件字节数',
    file_sha256 CHAR(64) NOT NULL COMMENT '文件SHA-256',
    file_content LONGBLOB NOT NULL COMMENT '文件完整二进制内容',
    oss_url VARCHAR(1000) DEFAULT NULL COMMENT '后续可选的OSS持久HTTPS地址',
    source_batch VARCHAR(100) NOT NULL COMMENT '导入批次',
    sort_order INT NOT NULL DEFAULT 100 COMMENT '展示顺序',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '0下架 1上架',
    is_deleted TINYINT NOT NULL DEFAULT 0 COMMENT '软删除',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zhongkao_resource_code (resource_code),
    UNIQUE KEY uk_zhongkao_resource_sha256 (file_sha256),
    KEY idx_zhongkao_resource_public (status, is_deleted, sort_order, id),
    KEY idx_zhongkao_resource_filter (resource_category, subject_category, target_year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='2026届中考志愿填报与自招资料文件';
