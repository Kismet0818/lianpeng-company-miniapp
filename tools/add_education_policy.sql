CREATE TABLE IF NOT EXISTS `education_policy` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `source_platform` varchar(50) NOT NULL DEFAULT 'anroader' COMMENT '数据来源平台',
  `source_id` bigint NOT NULL COMMENT '来源记录ID，用于去重和增量更新',
  `name` varchar(255) NOT NULL COMMENT '政策标题',
  `category` varchar(50) DEFAULT NULL COMMENT '特色分类：中考、高考、义务教育等',
  `education_level` varchar(30) DEFAULT NULL COMMENT '学段：小学、初中、高中等',
  `policy_type` varchar(50) DEFAULT NULL COMMENT '政策类型：招生政策、入学政策等',
  `province` varchar(50) DEFAULT NULL,
  `city` varchar(50) DEFAULT NULL,
  `address` varchar(255) DEFAULT NULL,
  `summary` text COMMENT '政策摘要',
  `content` longtext COMMENT '政策正文/说明',
  `cover_image_url` varchar(1000) DEFAULT NULL COMMENT '政策封面图片OSS地址',
  `public_date` datetime DEFAULT NULL COMMENT '发布日期',
  `policy_year` smallint DEFAULT NULL COMMENT '筛选年份',
  `status` varchar(30) NOT NULL DEFAULT '已发布',
  `source_create_time` datetime DEFAULT NULL,
  `source_update_time` datetime DEFAULT NULL,
  `sort_order` int NOT NULL DEFAULT 0,
  `is_deleted` tinyint NOT NULL DEFAULT 0,
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_policy_source` (`source_platform`,`source_id`),
  KEY `idx_policy_filter` (`is_deleted`,`status`,`category`,`policy_year`,`public_date`),
  KEY `idx_policy_level` (`education_level`),
  FULLTEXT KEY `ft_policy_search` (`name`,`summary`,`content`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='升学政策';

CREATE TABLE IF NOT EXISTS `education_policy_attachment` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `policy_id` bigint NOT NULL,
  `source_attachment_id` bigint DEFAULT NULL COMMENT '来源附件ID',
  `file_name` varchar(255) DEFAULT NULL,
  `file_path` varchar(500) NOT NULL COMMENT '来源返回的相对路径',
  `source_url` varchar(1000) DEFAULT NULL COMMENT '来源完整地址',
  `file_url` varchar(1000) DEFAULT NULL COMMENT '迁移到自有存储后的地址',
  `file_extension` varchar(20) DEFAULT NULL,
  `media_type` varchar(30) DEFAULT NULL COMMENT 'image、pdf、file',
  `is_cover` tinyint NOT NULL DEFAULT 0,
  `sort_order` int NOT NULL DEFAULT 0,
  `is_deleted` tinyint NOT NULL DEFAULT 0,
  `source_create_time` datetime DEFAULT NULL,
  `source_update_time` datetime DEFAULT NULL,
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_policy_attachment_source` (`policy_id`,`source_attachment_id`),
  KEY `idx_policy_attachment` (`policy_id`,`is_deleted`,`sort_order`),
  CONSTRAINT `fk_policy_attachment_policy` FOREIGN KEY (`policy_id`) REFERENCES `education_policy` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='升学政策附件';
