CREATE TABLE IF NOT EXISTS platform_content_link (
    id BIGINT NOT NULL AUTO_INCREMENT,
    content_type VARCHAR(32) NOT NULL COMMENT 'OFFICIAL_ACCOUNT or LIVE',
    title VARCHAR(200) NOT NULL,
    link_url VARCHAR(1000) NOT NULL,
    status TINYINT NOT NULL DEFAULT 1 COMMENT '1展示 0隐藏',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_platform_content_type (content_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='公众号与直播链接配置';
