CREATE TABLE IF NOT EXISTS admission_content_article (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    source_platform VARCHAR(50) NOT NULL DEFAULT 'kylx365' COMMENT '来源平台',
    source_category VARCHAR(50) NOT NULL COMMENT '来源栏目：详细文章/规划须知/志愿填报小知识',
    source_article_no VARCHAR(64) NOT NULL COMMENT '来源文章编号或稳定业务键',
    title VARCHAR(255) NOT NULL COMMENT '文章标题',
    article_year SMALLINT NULL COMMENT '文章年份，通用知识可为空',
    content_format VARCHAR(32) NOT NULL DEFAULT 'image_pages' COMMENT '内容形态',
    content_text LONGTEXT NULL COMMENT '已捕获的正文文本；未捕获时为空',
    source_url TEXT NULL COMMENT '来源文章或公开参考地址',
    image_urls JSON NOT NULL COMMENT '按页码排列的原始图片 URL 数组',
    local_image_files JSON NOT NULL COMMENT '待检查图片的本地相对路径数组',
    oss_image_urls JSON NULL COMMENT '按正文展示顺序排列的自有OSS图片URL数组',
    image_count INT NOT NULL DEFAULT 0 COMMENT '图片页数',
    capture_status VARCHAR(40) NOT NULL COMMENT 'complete/title_only',
    capture_note VARCHAR(500) NULL COMMENT '抓包完整性说明',
    sort_order INT NOT NULL DEFAULT 0 COMMENT '来源排序',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '启用状态：1启用，0停用',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_source_article (source_platform, source_category, source_article_no),
    KEY idx_category_year_sort (source_category, article_year, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='招生详细文章与志愿填报知识来源表';
