CREATE TABLE `primary_school` (
  `id` int NOT NULL AUTO_INCREMENT COMMENT '数据库主键ID，仅用于表内及关联表引用',
  `school_code` varchar(16) NOT NULL COMMENT '小学唯一业务编号，例如p001、p002',
  `source_school_id` int NOT NULL COMMENT '来源平台学校ID，用于幂等更新和去重',
  `name` varchar(100) NOT NULL COMMENT '学校全名',
  `short_name` varchar(100) DEFAULT NULL COMMENT '学校简称',
  `background_image_url` varchar(500) DEFAULT NULL COMMENT '学校背景图OSS完整URL',
  `district` varchar(50) NOT NULL COMMENT '所属区',
  `tuition_min` decimal(10,2) DEFAULT NULL COMMENT '最低学费（万元/年）',
  `tuition_max` decimal(10,2) DEFAULT NULL COMMENT '最高学费（万元/年）',
  `boarding_info` varchar(100) DEFAULT NULL COMMENT '寄宿情况',
  `school_type` varchar(20) NOT NULL COMMENT '学校性质：公办/民办',
  `tier` varchar(10) DEFAULT NULL COMMENT '学校梯队：一梯队/二梯队；不在名单中为NULL',
  `address` varchar(255) DEFAULT NULL COMMENT '学校地址',
  `description` text COMMENT '学校简介',
  `created_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `official_website` varchar(500) DEFAULT NULL COMMENT '学校官网',
  `schedule` text COMMENT '作息时间',
  `teaching_features` text COMMENT '教学特色',
  `campus_area` decimal(12,2) DEFAULT NULL COMMENT '占地面积（平方米）',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_primary_school_code` (`school_code`),
  UNIQUE KEY `uk_primary_school_source_id` (`source_school_id`),
  UNIQUE KEY `uk_primary_school_name_district` (`name`,`district`),
  KEY `idx_primary_school_district` (`district`),
  KEY `idx_primary_school_type` (`school_type`),
  KEY `idx_primary_school_tier` (`tier`),
  CONSTRAINT `chk_primary_school_code` CHECK ((regexp_like(`school_code`,_utf8mb4'^p[0-9]{3,}$'))),
  CONSTRAINT `chk_primary_school_tuition` CHECK (((`tuition_min` is null) or (`tuition_max` is null) or (`tuition_min` <= `tuition_max`))),
  CONSTRAINT `chk_primary_school_type` CHECK ((`school_type` in (_utf8mb4'公办',_utf8mb4'民办')))
) ENGINE=InnoDB AUTO_INCREMENT=100001 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='小学学校信息表（单表含背景图）';
