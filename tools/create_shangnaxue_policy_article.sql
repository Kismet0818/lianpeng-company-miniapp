CREATE TABLE IF NOT EXISTS `shangnaxue_policy_article` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `source_article_id` bigint NOT NULL COMMENT '上哪学文章ID',
  `related_article_id` bigint DEFAULT NULL,
  `thematic_id` bigint NOT NULL COMMENT '上哪学专题ID',
  `thematic_name` varchar(255) NOT NULL,
  `title` varchar(500) NOT NULL,
  `summary` longtext,
  `district` varchar(20) DEFAULT NULL COMMENT '由标题识别的上海行政区',
  `pic_url` varchar(1000) DEFAULT NULL,
  `article_url` varchar(1000) DEFAULT NULL,
  `wechat_url` varchar(1000) DEFAULT NULL,
  `platform_id` bigint DEFAULT NULL,
  `pub_time` datetime DEFAULT NULL,
  `source_update_time` datetime DEFAULT NULL,
  `browse_volume` int NOT NULL DEFAULT 0,
  `thumbs_up_num` int NOT NULL DEFAULT 0,
  `content_type` int DEFAULT NULL,
  `article_type` int DEFAULT NULL,
  `source_status` int DEFAULT NULL,
  `is_top` tinyint NOT NULL DEFAULT 0,
  `is_big` tinyint NOT NULL DEFAULT 0,
  `is_deleted` tinyint NOT NULL DEFAULT 0,
  `raw_json` json NOT NULL COMMENT 'HAR中该记录的完整原始JSON',
  `captured_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_snx_policy_source_article` (`source_article_id`),
  KEY `idx_snx_policy_thematic` (`thematic_id`,`is_deleted`,`source_status`),
  KEY `idx_snx_policy_district` (`district`),
  KEY `idx_snx_policy_pub_time` (`pub_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='上哪学入学政策专题文章来源表';
